"""Generate core/include/msf/diagnostics.inc from schemas/diagnostics.toml.

    python3 -B tools/gen_diagnostics.py          rewrite the header
    python3 -B tools/gen_diagnostics.py --check  exit 1 if it is stale

Removed codes are left out, so C++ cannot report them.
"""
from pathlib import Path
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "schemas" / "diagnostics.toml"
HEADER = ROOT / "core" / "include" / "msf" / "diagnostics.inc"


def render(registry):
    lines = ["// SPDX-License-Identifier: MIT",
             "// Generated by tools/gen_diagnostics.py from schemas/diagnostics.toml; do not edit.",
             "// MSF_DIAGNOSTIC(code, severity, strict): strict is the error that replaces a",
             "// warning under strict losses, or NONE."]
    for code in sorted(registry):
        entry = registry[code]
        if "removed" not in entry:
            lines.append(f"MSF_DIAGNOSTIC({code}, {entry['severity']}, {entry.get('strict', 'NONE')})")
    return "\n".join(lines) + "\n"


def main(argv):
    text = render(tomllib.loads(REGISTRY.read_text(encoding="utf-8")))
    if argv[1:] == ["--check"]:
        return 0 if HEADER.read_text(encoding="utf-8") == text else 1
    if argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    HEADER.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
